package study.console;
import org.junit.*;
import java.util.*;
import java.time.*;
import com.baomidou.mybatisplus.core.conditions.query.LambdaQueryWrapper;
import com.baomidou.mybatisplus.core.conditions.update.LambdaUpdateWrapper;
import org.apache.ibatis.exceptions.TooManyResultsException;
import static org.junit.Assert.*;
import static study.console.Database.Intent.*;
public class StudentBehaviorTest {
    private Database db;private StudentLab lab;
    @Before public void start(){db=Database.demo();lab=new StudentLab(db);}
    @After public void close(){db.close();}
    private Learner draft(String name){Learner x=new Learner();x.setName(name);x.setAge(20);x.setMajor("测试专业");x.setScore(72.0);return x;}
    @Test public void autogeneratedIdentityAndTimestamp(){
        Learner x=lab.enroll(draft("新增学生"));assertNotNull(x.getId());assertNotNull(x.getCreateTime());assertNotNull(x.getUpdateTime());assertEquals(Integer.valueOf(0),x.getVersion());assertEquals(Integer.valueOf(0),x.getDeleted());assertEquals(9,lab.count());
    }
    @Test public void providedInsertTimestampIsKept(){
        Learner x=draft("自带日期");LocalDateTime ancient=LocalDateTime.of(2002,4,1,8,0);x.setCreateTime(ancient);x.setUpdateTime(ancient);
        x=lab.enroll(x);assertEquals(ancient,x.getCreateTime());assertEquals(ancient,x.getUpdateTime());
    }
    @Test public void optimisticConflictDoesNotOverwrite(){
        Learner before=lab.find(1);Integer revision=before.getVersion();assertTrue(lab.changeScore(1,94.75,revision));
        assertFalse(lab.changeScore(1,10,revision));assertEquals(Double.valueOf(94.75),lab.find(1).getScore());assertEquals(Integer.valueOf(revision+1),lab.find(1).getVersion());
        assertFalse(lab.changeScore(999,80,null));
    }
    @Test public void updatingRefreshesTimestamp(){
        Learner x=draft("更新时间");x.setUpdateTime(LocalDateTime.of(2002,1,1,0,0));x=lab.enroll(x);assertTrue(lab.changeScore(x.getId(),88,null));assertTrue(lab.find(x.getId()).getUpdateTime().isAfter(x.getUpdateTime()));
    }
    @Test public void nullStrategyAndExplicitNullDiffer(){
        db.plusWork(REHEARSE,m->{Learner x=draft("字段策略");m.insert(x);Learner change=new Learner();change.setId(x.getId());change.setEmail("updated@example.com");change.setScore(null);m.updateById(change);
            assertEquals(Double.valueOf(72.0),m.selectById(x.getId()).getScore());
            m.update(null,new LambdaUpdateWrapper<Learner>().eq(Learner::getId,x.getId()).set(Learner::getScore,null));assertNull(m.selectById(x.getId()).getScore());return null;});
        assertEquals(8,lab.count());
    }
    @Test public void logicalBatchDeletionKeepsRows(){
        assertEquals(2,lab.expel(List.of(1L,2L)));assertNull(lab.find(1));assertEquals(6,lab.count());
        db.plusWork(READ,m->{assertEquals(Integer.valueOf(1),m.deletionFlag(1));assertTrue(m.selectByIds(List.of(1L,2L)).isEmpty());return null;});
    }
    @Test public void pageCountAndSlices(){
        var first=lab.page(1,3);var next=lab.page(2,3);assertEquals(8,first.getTotal());assertEquals(3,first.getRecords().size());
        assertTrue(Collections.disjoint(first.getRecords().stream().map(Learner::getId).toList(),next.getRecords().stream().map(Learner::getId).toList()));
        assertThrows(IllegalArgumentException.class,()->lab.page(0,3));
    }
    @Test public void filteredPaginationCountsOnlyMatchingRows(){
        var f=new StudentLab.Criteria();f.major="计算机";f.minimum=70.0;f.maximum=100.0;f.sort="score";
        var expected=lab.query(f,true).data().stream().map(Learner::getId).toList();
        assertTrue(expected.size()>1);
        for(boolean lambda:List.of(false,true)){
            var first=lab.page(1,1,f,lambda);var second=lab.page(2,1,f,lambda);
            assertEquals(expected.size(),first.getTotal());assertEquals(expected.size(),first.getPages());
            assertEquals(expected.get(0),first.getRecords().get(0).getId());assertEquals(expected.get(1),second.getRecords().get(0).getId());
            assertTrue(lab.page(99,1,f,lambda).getRecords().isEmpty());
        }
        f.minimum=101.0;assertThrows(IllegalArgumentException.class,()->lab.page(1,5,f,true));
    }
    @Test public void columnAndLambdaConditionsAgree(){
        var f=new StudentLab.Criteria();f.major="计算机";f.minimum=60.0;f.maximum=100.0;f.sort="score";
        var x=lab.query(f,false);var y=lab.query(f,true);assertEquals(x.data().stream().map(Learner::getId).toList(),y.data().stream().map(Learner::getId).toList());assertEquals(3,x.data().size());assertTrue(x.sql().contains("major"));
    }
    @Test public void groupedOrDoesNotLeakMajorConstraint(){
        var f=new StudentLab.Criteria();f.major="计算机";f.name="赵";f.alternativeAge=21;
        var x=lab.query(f,false).data();var y=lab.query(f,true).data();assertEquals(2,x.size());assertEquals(x.stream().map(Learner::getId).toList(),y.stream().map(Learner::getId).toList());assertTrue(x.stream().allMatch(s->s.getMajor().equals("计算机")));
    }
    @Test public void wildcardPatternsAndIn(){
        var f=new StudentLab.Criteria();f.name="赵";f.pattern=StudentLab.Pattern.STARTS_WITH;assertEquals(1,lab.query(f,false).data().size());assertEquals(1,lab.query(f,true).data().size());
        f.name="川";f.pattern=StudentLab.Pattern.ENDS_WITH;assertEquals(1,lab.query(f,true).data().size());
        f.name=null;f.majors=List.of("计算机","人工智能");assertEquals(5,lab.query(f,false).data().size());assertEquals(5,lab.query(f,true).data().size());
    }
    @Test public void slimMapsAndAggregateQueries(){
        var slim=lab.slim(new StudentLab.Criteria()).data();assertEquals(8,slim.size());assertNull(slim.get(0).getEmail());assertNull(slim.get(0).getAge());
        assertEquals(8,lab.maps(new StudentLab.Criteria()).data().size());assertEquals(3,lab.stats().size());assertEquals(3,lab.grouped().size());assertEquals(3,lab.count("计算机"));
        var top=lab.top(80,2);assertEquals(2,top.size());assertTrue(top.get(0).getScore()>=top.get(1).getScore());
    }
    @Test public void exactAndSingleRowContracts(){
        assertEquals(1,lab.exact(Map.of("major","计算机","age",19)).size());assertNotNull(lab.unique("赵明川"));assertEquals(1,lab.occurrences("赵明川"));assertNull(lab.unique("不存在"));
        assertThrows(IllegalArgumentException.class,()->lab.exact(Map.of()));
        lab.enroll(draft("同名"));lab.enroll(draft("同名"));assertThrows(TooManyResultsException.class,()->lab.unique("同名"));
    }
    @Test public void bulkUpdateAndSafetyGuard(){
        assertEquals(3,lab.raise("计算机",100,99.5));assertTrue(lab.exact(Map.of("major","计算机")).stream().allMatch(x->x.getScore()==99.5));
        assertThrows(IllegalArgumentException.class,()->lab.raise(null,80,90));
        assertThrows(RuntimeException.class,()->db.plusWork(COMMIT,m->{Learner x=new Learner();x.setScore(0.0);return m.update(x,null);}));assertEquals(8,lab.count());
    }
    @Test public void transactionExperimentsRestoreValues(){
        var scores=lab.query(new StudentLab.Criteria(),false).data().stream().map(Learner::getScore).toList();
        var demo=lab.rehearse();assertEquals(0,demo.get("staleUpdated"));assertEquals(1,demo.get("deletedFlag"));assertEquals(8,lab.count());
        var wrapper=lab.rehearseWrappers();assertEquals("explicit null",true,wrapper.get("explicitNull"));assertEquals("duplicate result rejected",true,wrapper.get("duplicateRejected"));assertEquals(Double.valueOf(96.0),wrapper.get("preservedScore"));
        assertEquals(scores,lab.query(new StudentLab.Criteria(),false).data().stream().map(Learner::getScore).toList());
    }
    @Test public void resetOnlyStudentDomain(){lab.expel(List.of(1L));lab.reset();assertEquals(8,lab.count());assertNotNull(lab.find(1));assertEquals(18,new Organization(db).search(Map.of()).size());}
    @Test public void invalidConditionsFailBeforeSql(){var f=new StudentLab.Criteria();f.minimum=100.0;f.maximum=1.0;assertThrows(IllegalArgumentException.class,()->lab.query(f,false));f.minimum=null;f.maximum=null;f.sort="id;DROP TABLE learner";assertThrows(IllegalArgumentException.class,()->lab.query(f,true));}
}
